#!/usr/bin/env bash
# Register the three news-watch Hermes cron jobs (idempotent).
#   news-daily-collect    08:00 Mon-Fri  agent mode, local delivery (vault digest)
#   newswatch-morning     08:30 Mon-Fri  no-agent, Telegram
#   newswatch-after-close 15:15 Mon-Fri  no-agent, Telegram
# Usage: scripts/register_newswatch_cron.sh [--dry-run]
#
# Hermes only runs job scripts that resolve inside ~/.hermes/scripts/ (symlinks
# are resolved and blocked), so this writes a small real Python wrapper there
# per job script. Each wrapper has the absolute repo paths baked in and execs
# backend/.venv/bin/python on the repo script. Re-run after moving the repo.
set -euo pipefail

DRY_RUN=0
case "${1:-}" in
  "") ;;
  --dry-run) DRY_RUN=1 ;;
  *) echo "usage: $0 [--dry-run]" >&2; exit 2 ;;
esac

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HERMES_SCRIPTS="$HOME/.hermes/scripts"
PYTHON="$SCRIPT_DIR/../backend/.venv/bin/python"
PYTHON="$(cd "$(dirname "$PYTHON")" && pwd)/$(basename "$PYTHON")"
TZ_NAME="Asia/Ho_Chi_Minh"
SCRIPTS=(collect_daily_news.py newswatch_morning.py newswatch_after_close.py)

# Paths are embedded in Python string literals below.
for p in "$SCRIPT_DIR" "$PYTHON"; do
  case "$p" in
    *\"*|*\\*|*$'\n'*) echo "unsupported character in path: $p" >&2; exit 1 ;;
  esac
done

run() {
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '[dry-run]'; printf ' %q' "$@"; printf '\n'
  else
    "$@"
  fi
}

wrapper_body() {
  local target="$1"
  cat <<EOF
#!/usr/bin/env python3
# Generated by register_newswatch_cron.sh — do not edit; re-run that script
# after moving the repo. Hermes blocks symlinks out of ~/.hermes/scripts, so
# this real file execs the repo script under the backend venv.
import os
import sys

PYTHON = "$PYTHON"
SCRIPT = "$target"
os.environ.pop("PYTHONPATH", None)
os.environ.pop("PYTHONHOME", None)
os.execv(PYTHON, [PYTHON, SCRIPT, *sys.argv[1:]])
EOF
}

write_wrapper() {
  local name="$1"
  local dest="$HERMES_SCRIPTS/$name"
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "[dry-run] write $dest:"
    wrapper_body "$SCRIPT_DIR/$name" | sed 's/^/    /'
    return 0
  fi
  local tmp
  tmp="$(mktemp "$HERMES_SCRIPTS/.$name.XXXXXX")"
  wrapper_body "$SCRIPT_DIR/$name" > "$tmp"
  chmod 755 "$tmp"
  # mv replaces an old symlink at $dest with the real file
  mv -f "$tmp" "$dest"
  echo "wrote $dest"
}

run mkdir -p "$HERMES_SCRIPTS"
for s in "${SCRIPTS[@]}"; do
  if [ ! -f "$SCRIPT_DIR/$s" ]; then
    echo "missing repo script: $SCRIPT_DIR/$s" >&2; exit 1
  fi
  write_wrapper "$s"
done

if ! EXISTING="$(hermes cron list --all 2>&1)"; then
  echo "hermes cron list --all failed; not registering anything:" >&2
  printf '%s\n' "$EXISTING" >&2
  exit 1
fi
# Exact job names from the "Name:" rows (ANSI colour codes stripped).
EXISTING_NAMES="$(printf '%s\n' "$EXISTING" \
  | sed -e $'s/\x1b\\[[0-9;]*m//g' \
  | sed -n 's/^[[:space:]]*Name:[[:space:]]*//p' \
  | sed 's/[[:space:]]*$//')"

FAILED=0
create_job() {
  local name="$1"; shift
  if printf '%s\n' "$EXISTING_NAMES" | grep -qxF -- "$name"; then
    echo "skip: $name already registered"
    return 0
  fi
  if ! run hermes cron create --name "$name" --timezone "$TZ_NAME" \
      --interpreter "$PYTHON" --catch-up off "$@"; then
    echo "failed to create $name" >&2
    FAILED=1
  fi
}

DIGEST_PROMPT="Read today's vault note path from the script output. Fill in the Day Summary and a summary for each article in that note, then set processed: true in its frontmatter."

create_job news-daily-collect "0 8 * * 1-5" "$DIGEST_PROMPT" \
  --script collect_daily_news.py --deliver local

create_job newswatch-morning "30 8 * * 1-5" \
  --script newswatch_morning.py --no-agent \
  --deliver telegram --failure-deliver local

create_job newswatch-after-close "15 15 * * 1-5" \
  --script newswatch_after_close.py --no-agent \
  --deliver telegram --failure-deliver local

run hermes cron list
exit "$FAILED"
